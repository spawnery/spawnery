#!/usr/bin/env bash
# Renders docs/reference/metrics-and-alerts.md from two sources that only
# agree with each other if this script checks: the metrics the operator
# actually registers, from internal/docsgen/metrics, and the alerting rules
# in charts/spawnery/templates/prometheusrule.yaml, rendered through `helm
# template` because that file is a Helm chart template, not YAML, until Helm
# has expanded it.
#
# Run by `make manifests`, after hack/chart-values-docs.sh. Same shape as its
# two siblings: a thin bash entry point, with the part that needs a real
# YAML parser (the alerts) in embedded Python and the part that needs the
# running metrics registry (the metrics) in the Go program beside this
# script.
set -euo pipefail

cd "$(dirname "$0")/.."

out="docs/reference/metrics-and-alerts.md"
tmp_metrics="$(mktemp)"
tmp_rules="$(mktemp)"
trap 'rm -f "$tmp_metrics" "$tmp_rules"' EXIT

go run ./internal/docsgen/metrics >"$tmp_metrics"

# --namespace is arbitrary -- nothing on this page reads it -- but a
# namespaced resource needs one to render at all.
helm template spawnery charts/spawnery \
	--namespace spawnery-system \
	--set metrics.prometheusRule.enabled=true \
	>"$tmp_rules"

python3 - "$tmp_metrics" "$tmp_rules" "$out" <<'PY'
import html
import re
import sys

import yaml

metrics_path, rules_path, out_path = sys.argv[1], sys.argv[2], sys.argv[3]

HEADER = (
    "<!-- Generated by `hack/metrics-docs.sh` via `make manifests`. Do not\n"
    "     edit: your changes are lost the next time it runs. -->"
)

with open(metrics_path) as f:
    metrics_table = f.read().strip()

# The metrics table's own Name column, not a second query against the
# registry: this is the exact set of names the page above is about to claim
# it documents, and an alert naming anything else is a rule that can never
# fire.
documented = set(re.findall(r"<code>(spawnery_[A-Za-z0-9_]*)</code>", metrics_table))
if not documented:
    sys.exit(f"metrics-docs: no metric names found in {metrics_path}")

with open(rules_path) as f:
    rendered = f.read()

rule = None
for doc in yaml.safe_load_all(rendered):
    if isinstance(doc, dict) and doc.get("kind") == "PrometheusRule":
        rule = doc
        break
if rule is None:
    sys.exit(
        "metrics-docs: `helm template` produced no PrometheusRule -- check "
        "metrics.prometheusRule.enabled in the invocation above"
    )

alerts = []
for group in rule["spec"]["groups"]:
    for r in group.get("rules", []):
        if "alert" not in r:
            continue
        alerts.append({
            "group": group["name"],
            "name": r["alert"],
            "expr": r["expr"].strip(),
            "for": r.get("for", ""),
            "severity": r.get("labels", {}).get("severity", ""),
            "summary": (r.get("annotations", {}).get("summary") or "").strip(),
            "description": (r.get("annotations", {}).get("description") or "").strip(),
        })
if not alerts:
    sys.exit(f"metrics-docs: the rendered PrometheusRule in {rules_path} carries no alerts")
alerts.sort(key=lambda a: a["name"])

# The check this generator exists for: a PromQL expression naming a metric
# the operator does not export is a rule that can never fire. The names all
# start spawnery_, which is all a regex needs to pull them out of an
# expression -- PromQL syntax around a metric name (label matchers, range
# selectors, aggregation functions) never itself starts with that prefix, so
# nothing about parsing the rest of the expression is needed here. A vector
# match on a *different* Prometheus's metric (none of these alerts have one)
# would be the case this shortcut cannot see through.
undocumented = {}
for a in alerts:
    for name in re.findall(r"spawnery_[A-Za-z0-9_]*", a["expr"]):
        if name not in documented:
            undocumented.setdefault(a["name"], set()).add(name)
if undocumented:
    lines = [
        f"  {alert}: {', '.join(sorted(names))}"
        for alert, names in sorted(undocumented.items())
    ]
    sys.exit(
        "metrics-docs: alert(s) reference metric(s) absent from the metrics "
        "table above -- a rule that can never fire:\n" + "\n".join(lines)
    )


def render_paragraphs(text):
    paragraphs = [p.strip() for p in text.split("\n\n") if p.strip()]
    rendered = []
    for p in paragraphs:
        rendered.append(html.escape(" ".join(line.strip() for line in p.splitlines())))
    return rendered


def render_alert(a):
    lines = [f"### {a['name']}", ""]
    lines.append(
        f"**Group:** <code>{html.escape(a['group'])}</code> &nbsp;&nbsp; "
        f"**Severity:** <code>{html.escape(a['severity'])}</code> &nbsp;&nbsp; "
        f"**For:** <code>{html.escape(a['for'])}</code>"
    )
    lines.append("")
    for p in render_paragraphs(a["summary"]):
        lines.append(p)
        lines.append("")
    lines.append("```")
    lines.append(a["expr"])
    lines.append("```")
    lines.append("")
    for p in render_paragraphs(a["description"]):
        lines.append(p)
        lines.append("")
    return "\n".join(lines).rstrip("\n")


out = [HEADER, "", "# Metrics and alerts", ""]
out.append(
    "Generated from two sources that only agree with each other because "
    "this page checks it: the Prometheus metrics the operator actually "
    "registers, read from `sigs.k8s.io/controller-runtime`'s metrics "
    "registry rather than from source, so this table can't drift from what "
    "is really exported; and the alerting rules in "
    "`charts/spawnery/templates/prometheusrule.yaml`, rendered through "
    "`helm template` because that file is a Helm chart template, not YAML, "
    "until Helm has expanded it."
)
out.append("")
out.append("## Metrics")
out.append("")
out.append(metrics_table)
out.append("")
out.append("## Alerts")
out.append("")
out.append(
    "Off by default (`metrics.prometheusRule.enabled: false`, see "
    "[chart values](chart-values.md)); rendered here with that value turned "
    "on and every other value left at the chart's own default. "
    "`SpawneryCAExpiringSoon`'s summary interpolates "
    "`metrics.prometheusRule.caExpiryWarningDays` -- the number in it below "
    "is that value's chart *default*, not a fixed part of the alert; an "
    "install that overrides it gets a different number in that one message."
)
out.append("")

for a in alerts:
    out.append(render_alert(a))
    out.append("")

with open(out_path, "w") as f:
    f.write("\n".join(out).rstrip("\n") + "\n")
PY

echo "wrote $out"
