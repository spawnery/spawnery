#!/usr/bin/env bash
# Renders docs/reference/metrics-and-alerts.md from the metrics the operator
# registers (internal/docsgen/metrics) and the alerting rules in the chart, and
# refuses an alert naming a metric the operator does not export.
set -euo pipefail

cd "$(dirname "$0")/.."

out="docs/reference/metrics-and-alerts.md"
tmp_metrics="$(mktemp)"
tmp_rules="$(mktemp)"
trap 'rm -f "$tmp_metrics" "$tmp_rules"' EXIT

go run ./internal/docsgen/metrics >"$tmp_metrics"

# --namespace is arbitrary; a namespaced resource needs one to render.
# World sync on, so its rules render; it needs an object store to render at all.
helm template spawnery charts/spawnery \
	--namespace spawnery-system \
	--set metrics.prometheusRule.enabled=true \
	--set worldSync.enabled=true \
	--set worldSync.objectStore.endpoint=https://s3.example \
	--set worldSync.objectStore.region=r \
	--set worldSync.objectStore.bucket=b \
	--set worldSync.objectStore.credentialsSecret=creds \
	>"$tmp_rules"

python3 - "$tmp_metrics" "$tmp_rules" "$out" <<'PY'
import html
import re
import sys

import yaml

metrics_path, rules_path, out_path = sys.argv[1], sys.argv[2], sys.argv[3]

HEADER = (
    "<!-- Generated by `hack/metrics-docs.sh` via `make manifests`. Do not\n"
    "     edit: your changes are lost the next time it runs. -->"
)

with open(metrics_path) as f:
    metrics_table = f.read().strip()

documented = set(re.findall(r"<code>(spawnery_[A-Za-z0-9_]*)</code>", metrics_table))
if not documented:
    sys.exit(f"metrics-docs: no metric names found in {metrics_path}")

with open(rules_path) as f:
    rendered = f.read()

rule = None
for doc in yaml.safe_load_all(rendered):
    if isinstance(doc, dict) and doc.get("kind") == "PrometheusRule":
        rule = doc
        break
if rule is None:
    sys.exit(
        "metrics-docs: `helm template` produced no PrometheusRule -- check "
        "metrics.prometheusRule.enabled in the invocation above"
    )

alerts = []
for group in rule["spec"]["groups"]:
    for r in group.get("rules", []):
        if "alert" not in r:
            continue
        alerts.append({
            "group": group["name"],
            "name": r["alert"],
            "expr": r["expr"].strip(),
            "for": r.get("for", ""),
            "severity": r.get("labels", {}).get("severity", ""),
            "summary": (r.get("annotations", {}).get("summary") or "").strip(),
            "description": (r.get("annotations", {}).get("description") or "").strip(),
        })
if not alerts:
    sys.exit(f"metrics-docs: the rendered PrometheusRule in {rules_path} carries no alerts")
alerts.sort(key=lambda a: a["name"])

# No PromQL parser needed: nothing around a metric name starts with spawnery_.
undocumented = {}
for a in alerts:
    for name in re.findall(r"spawnery_[A-Za-z0-9_]*", a["expr"]):
        if name not in documented:
            undocumented.setdefault(a["name"], set()).add(name)
if undocumented:
    lines = [
        f"  {alert}: {', '.join(sorted(names))}"
        for alert, names in sorted(undocumented.items())
    ]
    sys.exit(
        "metrics-docs: alert(s) reference metric(s) absent from the metrics "
        "table above -- a rule that can never fire:\n" + "\n".join(lines)
    )


def render_paragraphs(text):
    paragraphs = [p.strip() for p in text.split("\n\n") if p.strip()]
    rendered = []
    for p in paragraphs:
        rendered.append(html.escape(" ".join(line.strip() for line in p.splitlines())))
    return rendered


def render_alert(a):
    lines = [f"### {a['name']}", ""]
    lines.append(
        f"**Group:** <code>{html.escape(a['group'])}</code> &nbsp;&nbsp; "
        f"**Severity:** <code>{html.escape(a['severity'])}</code> &nbsp;&nbsp; "
        f"**For:** <code>{html.escape(a['for'])}</code>"
    )
    lines.append("")
    for p in render_paragraphs(a["summary"]):
        lines.append(p)
        lines.append("")
    lines.append("```")
    lines.append(a["expr"])
    lines.append("```")
    lines.append("")
    for p in render_paragraphs(a["description"]):
        lines.append(p)
        lines.append("")
    return "\n".join(lines).rstrip("\n")


out = [HEADER, "", "# Metrics and alerts", ""]
out.append(
    "Generated from two sources that only agree with each other because "
    "this page checks it: the Prometheus metrics the operator and the world "
    "sync node agent actually register, read from their registries rather "
    "than from source, so this table can't drift from what is really "
    "exported; and the alerting rules in "
    "`charts/spawnery/templates/prometheusrule.yaml`, rendered through "
    "`helm template` because that file is a Helm chart template, not YAML, "
    "until Helm has expanded it."
)
out.append("")
out.append("## Metrics")
out.append("")
out.append(
    "The `spawnery_worldsync_` metrics come from the world sync node agents "
    "on port 8090, the rest from the operator on port 8080."
)
out.append("")
out.append(metrics_table)
out.append("")
out.append("## Alerts")
out.append("")
out.append(
    "Off by default (`metrics.prometheusRule.enabled: false`, see "
    "[chart values](chart-values.md)); rendered here with that value and "
    "`worldSync.enabled` turned on and every other value left at the "
    "chart's own default. The `spawnery-worldsync` group renders only with "
    "world sync on. "
    "`SpawneryCAExpiringSoon`'s summary interpolates "
    "`metrics.prometheusRule.caExpiryWarningDays` -- the number in it below "
    "is that value's chart *default*, not a fixed part of the alert; an "
    "install that overrides it gets a different number in that one message."
)
out.append("")

for a in alerts:
    out.append(render_alert(a))
    out.append("")

with open(out_path, "w") as f:
    f.write("\n".join(out).rstrip("\n") + "\n")
PY

echo "wrote $out"
