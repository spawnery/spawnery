python3 - "$crd_dir" "$out" <<'PY'
import glob
import html
import re
import sys

import yaml

crd_dir, out_path = sys.argv[1], sys.argv[2]

HEADER = (
    "<!-- Generated by `hack/crd-docs.sh` via `make manifests`. Do not edit:\n"
    "     your changes are lost the next time it runs. -->"
)

K8S_API_DOC = "https://pkg.go.dev/k8s.io/api/core/v1"

# The stop-list. Each entry is a field spawnery's own CRDs embed by reference
# from a Kubernetes API type rather than declaring themselves -- the fields
# under it are the upstream type's, documented at the linked URL, and
# expanding them here would bury spawnery's own ~250 fields under a couple of
# hundred rows of PodAffinityTerm and EnvVarSource that kubernetes.io already
# covers. affinity/tolerations/resources account for the bulk of it (97, 6
# and 6 properties per occurrence); valueFrom and the two volume sources under
# mounts are smaller but the same kind of field, by the same test: none of
# their sub-fields is declared in this repository's own API package.
#
# A path belongs here only when its whole subtree is a Kubernetes type this
# repository does not declare -- not when it merely sits next to one or is
# named after one. spec.mounts[].persistentVolumeClaim reads like
# corev1.PersistentVolumeClaimVolumeSource and is not: it is spawnery's own
# MountClaim (api/v1alpha1/common_types.go), whose Writable field has no
# upstream counterpart and is exactly the kind of field this page exists to
# surface. It stays expanded. Network.spec.scheduling is the same trap from
# the other direction -- named like the Kubernetes-facing scheduling defaults
# next to it, but its own guardrail type (allowedAffinityNamespaces,
# hostPortRange, ...) -- and also stays expanded.
#
# Kept as (kind, path) pairs, not bare paths, the same bargain
# internal/rbacaudit/required.go makes: the walk below marks an entry seen
# only when it finds that exact path in that exact kind's schema, so a field
# renamed or moved out from under a kind turns this table's own check red
# rather than silently expanding two hundred rows into the page.
STOP_LIST = [
    ("Network", "spec.defaults.scheduling.affinity", "Affinity", f"{K8S_API_DOC}#Affinity"),
    ("Network", "spec.defaults.scheduling.tolerations", "[]Toleration", f"{K8S_API_DOC}#Toleration"),
    ("Network", "spec.defaults.resources", "ResourceRequirements", f"{K8S_API_DOC}#ResourceRequirements"),
    ("ProxyGroup", "spec.scheduling.affinity", "Affinity", f"{K8S_API_DOC}#Affinity"),
    ("ProxyGroup", "spec.scheduling.tolerations", "[]Toleration", f"{K8S_API_DOC}#Toleration"),
    ("ProxyGroup", "spec.resources", "ResourceRequirements", f"{K8S_API_DOC}#ResourceRequirements"),
    ("ProxyGroup", "spec.env[].valueFrom", "EnvVarSource", f"{K8S_API_DOC}#EnvVarSource"),
    ("ProxyGroup", "spec.mounts[].configMap", "ConfigMapVolumeSource", f"{K8S_API_DOC}#ConfigMapVolumeSource"),
    ("ProxyGroup", "spec.mounts[].secret", "SecretVolumeSource", f"{K8S_API_DOC}#SecretVolumeSource"),
    ("ServerGroup", "spec.scheduling.affinity", "Affinity", f"{K8S_API_DOC}#Affinity"),
    ("ServerGroup", "spec.scheduling.tolerations", "[]Toleration", f"{K8S_API_DOC}#Toleration"),
    ("ServerGroup", "spec.resources", "ResourceRequirements", f"{K8S_API_DOC}#ResourceRequirements"),
    ("ServerGroup", "spec.env[].valueFrom", "EnvVarSource", f"{K8S_API_DOC}#EnvVarSource"),
    ("ServerGroup", "spec.mounts[].configMap", "ConfigMapVolumeSource", f"{K8S_API_DOC}#ConfigMapVolumeSource"),
    ("ServerGroup", "spec.mounts[].secret", "SecretVolumeSource", f"{K8S_API_DOC}#SecretVolumeSource"),
]
STOP_BY_KEY = {(k, p): (label, url) for k, p, label, url in STOP_LIST}

# The order the rest of the site already tells this story in (see
# CLAUDE.md's "What this is"): the network first, the two group kinds that
# fill it, the per-pod object those groups own, and the auxiliary object
# last.
KIND_ORDER = ["Network", "ServerGroup", "ProxyGroup", "Server", "ScaleBoost"]

URL_RE = re.compile(r"https?://[^\s<>\"]+")
CODE_SPAN_RE = re.compile(r"`([^`]+)`")


def load_crds(directory):
    by_kind = {}
    for path in sorted(glob.glob(f"{directory}/*.yaml")):
        with open(path) as f:
            doc = yaml.safe_load(f)
        names = doc["spec"]["names"]
        version = doc["spec"]["versions"][0]
        schema = version["schema"]["openAPIV3Schema"]
        by_kind[names["kind"]] = {
            "file": path,
            "kind": names["kind"],
            "plural": names["plural"],
            "shortNames": names.get("shortNames", []),
            "scope": doc["spec"]["scope"],
            "description": schema.get("description", ""),
            "printerColumns": version.get("additionalPrinterColumns", []),
            "spec": schema["properties"].get("spec", {}),
            "status": schema["properties"].get("status", {}),
        }
    return by_kind


def render_description(text):
    if not text:
        return ""
    paragraphs = [p.strip() for p in text.strip().split("\n\n") if p.strip()]
    rendered = []
    for p in paragraphs:
        p = " ".join(line.strip() for line in p.splitlines())
        p = html.escape(p)
        p = CODE_SPAN_RE.sub(lambda m: f"<code>{m.group(1)}</code>", p)
        p = URL_RE.sub(lambda m: f'<a href="{m.group(0)}">{m.group(0)}</a>', p)
        rendered.append(p)
    if len(rendered) <= 1:
        return rendered[0] if rendered else ""
    # These doc comments are paragraph-structured -- the blank line between
    # paragraphs is already meaningful, since that is what "<br><br>" above
    # renders -- so the first paragraph is a cut that never lands mid-thought.
    # A table where most rows are one sentence and a few run to 300 words is
    # not scannable with all of it visible at once; a single-paragraph
    # description is left alone; there is nothing to collapse and no reason
    # to invite a click into an empty "more".
    first, rest = rendered[0], rendered[1:]
    return first + "<details><summary>more</summary>" + "<br><br>".join(rest) + "</details>"


def type_of(schema):
    """The base type name, without constraints. Recurses into array item
    types so 'array of string' and 'array of object' are both meaningful."""
    t = schema.get("type")
    if t == "array":
        items = schema.get("items", {}) or {}
        if items.get("type") == "object" and "properties" in items:
            return "array"
        return f"array of {type_of(items)}" if items else "array"
    if t == "object" or t is None:
        if "properties" in schema:
            return "object"
        ap = schema.get("additionalProperties")
        if isinstance(ap, dict):
            return f"map[string]{type_of(ap)}"
        return "map[string]string" if ap else "object"
    fmt = schema.get("format")
    return f"{t} ({fmt})" if fmt else t


def constraints_of(schema):
    notes = []
    if "enum" in schema:
        notes.append("one of: " + ", ".join(str(v) for v in schema["enum"]))
    if "minimum" in schema or "maximum" in schema:
        lo, hi = schema.get("minimum"), schema.get("maximum")
        notes.append(f"{lo if lo is not None else ''}-{hi}" if hi is not None else f">= {lo}")
    if "minLength" in schema or "maxLength" in schema:
        lo, hi = schema.get("minLength"), schema.get("maxLength")
        notes.append(f"length {lo if lo is not None else 0}-{hi}" if hi is not None else f"length >= {lo}")
    if "minItems" in schema:
        notes.append(f"at least {schema['minItems']} item(s)")
    if "pattern" in schema:
        notes.append(f"pattern <code>{html.escape(schema['pattern'])}</code>")
    return notes


def type_cell(schema):
    base = type_of(schema)
    notes = constraints_of(schema)
    if not notes:
        return html.escape(base)
    return f"{html.escape(base)} ({'; '.join(n if '<code>' in n else html.escape(n) for n in notes)})"


def default_cell(schema):
    if "default" not in schema:
        return ""
    d = schema["default"]
    if isinstance(d, bool):
        text = "true" if d else "false"
    elif d is None:
        text = "null"
    elif isinstance(d, (dict, list)):
        # A wide dump, not the default ~80 columns: PyYAML line-wraps a long
        # flow-style value with a backslash continuation, which is unreadable
        # once html-escaped into a single table cell.
        text = yaml.safe_dump(d, default_flow_style=True, sort_keys=False, width=10**6).strip()
    else:
        text = str(d)
    return f"<code>{html.escape(text)}</code>"


def walk(kind, props, required, prefix, rows, seen_stops):
    for name, schema in (props or {}).items():
        path = f"{prefix}.{name}"
        is_required = name in required
        stop_key = (kind, path)
        if stop_key in STOP_BY_KEY:
            seen_stops.add(stop_key)
            label, url = STOP_BY_KEY[stop_key]
            rows.append({
                "path": path,
                "type": f'<a href="{html.escape(url)}">{html.escape(label)}</a> (Kubernetes, not expanded here)',
                "required": is_required,
                "default": default_cell(schema),
                "description": render_description(schema.get("description", "")),
            })
            continue
        rows.append({
            "path": path,
            "type": type_cell(schema),
            "required": is_required,
            "default": default_cell(schema),
            "description": render_description(schema.get("description", "")),
        })
        t = schema.get("type")
        if t == "object" and "properties" in schema:
            walk(kind, schema["properties"], set(schema.get("required", [])), path, rows, seen_stops)
        elif t == "array":
            items = schema.get("items", {}) or {}
            if items.get("type") == "object" and "properties" in items:
                walk(kind, items["properties"], set(items.get("required", [])), path + "[]", rows, seen_stops)


def relative(prefix, path):
    return path[len(prefix) + 1:]


def render_field_table(prefix, rows):
    if not rows:
        return "*None.*\n"
    # No blank lines inside the block: Python-Markdown treats a tag opening a
    # line as a raw HTML block only while every following line stays part of
    # the same block, and a blank line ends that early, leaving `<table>`
    # onward parsed as a paragraph of literal text instead of HTML.
    out = ['<div style="overflow-x: auto;"><table>']
    out.append("<thead><tr><th>Field</th><th>Type</th><th>Required</th><th>Default</th><th>Description</th></tr></thead>")
    out.append("<tbody>")
    for row in rows:
        field = html.escape(relative(prefix, row["path"]))
        required = "&#10003;" if row["required"] else ""
        out.append(
            "<tr>"
            f"<td><code>{field}</code></td>"
            f"<td>{row['type']}</td>"
            f'<td align="center">{required}</td>'
            f"<td>{row['default']}</td>"
            f"<td>{row['description']}</td>"
            "</tr>"
        )
    out.append("</tbody></table></div>")
    return "\n".join(out)


def render_printer_columns(columns):
    if not columns:
        return "*None.*\n"
    out = ['<div style="overflow-x: auto;"><table>']
    out.append("<thead><tr><th>Column</th><th>Type</th><th>JSONPath</th></tr></thead>")
    out.append("<tbody>")
    for col in columns:
        out.append(
            "<tr>"
            f"<td>{html.escape(col['name'])}</td>"
            f"<td>{html.escape(col.get('type', ''))}</td>"
            f"<td><code>{html.escape(col['jsonPath'])}</code></td>"
            "</tr>"
        )
    out.append("</tbody></table></div>")
    return "\n".join(out)


def render_kind(crd, seen_stops):
    lines = []
    kind = crd["kind"]
    lines.append(f"## {kind}")
    lines.append("")
    short_names = ", ".join(f"`{s}`" for s in crd["shortNames"]) or "*none*"
    lines.append(f"**Scope:** {crd['scope']} &nbsp;&nbsp; **Plural:** `{crd['plural']}` &nbsp;&nbsp; **Short names:** {short_names}")
    lines.append("")
    if crd["description"]:
        lines.append(render_description(crd["description"]))
        lines.append("")
    lines.append("### What `kubectl get` shows")
    lines.append("")
    lines.append(render_printer_columns(crd["printerColumns"]))
    lines.append("")

    spec_rows = []
    spec_schema = crd["spec"]
    walk(kind, spec_schema.get("properties", {}), set(spec_schema.get("required", [])), "spec", spec_rows, seen_stops)
    lines.append("### spec")
    lines.append("")
    if spec_schema.get("description"):
        lines.append(render_description(spec_schema["description"]))
        lines.append("")
    lines.append(render_field_table("spec", spec_rows))
    lines.append("")

    status_schema = crd["status"]
    if status_schema.get("properties"):
        status_rows = []
        walk(kind, status_schema.get("properties", {}), set(status_schema.get("required", [])), "status", status_rows, seen_stops)
        lines.append("### status")
        lines.append("")
        lines.append("Read by observers; the operator writes it and reads nothing back from it.")
        lines.append("")
        lines.append(render_field_table("status", status_rows))
        lines.append("")

    return "\n".join(lines)


def main():
    by_kind = load_crds(crd_dir)
    missing = [k for k in KIND_ORDER if k not in by_kind]
    if missing:
        sys.exit(f"crd-docs: expected kinds {missing} not found under {crd_dir}")
    extra = [k for k in by_kind if k not in KIND_ORDER]
    if extra:
        sys.exit(f"crd-docs: {crd_dir} carries kind(s) {extra} that KIND_ORDER in hack/crd-docs.sh does not know about")

    seen_stops = set()
    out = [HEADER, "", "# Custom resources", ""]
    out.append(
        "Generated from `config/crd/bases/*.yaml` -- the same schema `kubectl explain` and "
        "`kubectl apply --validate` read. Five namespaced kinds in `spawnery.cloud/v1alpha1`."
    )
    out.append("")
    out.append(
        "A few fields are Kubernetes' own types, embedded by reference rather than declared in "
        "this repository: they appear as a single row naming the type and linking to "
        "[the Go package reference for `k8s.io/api/core/v1`](" + K8S_API_DOC + ") instead of "
        "being expanded here."
    )
    out.append("")
    out.append("- " + "\n- ".join(f"[{k}](#{k.lower()})" for k in KIND_ORDER))
    out.append("")

    for kind in KIND_ORDER:
        out.append(render_kind(by_kind[kind], seen_stops))
        out.append("")

    unseen = [key for key in STOP_BY_KEY if key not in seen_stops]
    if unseen:
        sys.exit(
            "crd-docs: stop-list entries no longer resolve against the CRDs: "
            + ", ".join(f"{k}:{p}" for k, p in unseen)
        )

    with open(out_path, "w") as f:
        f.write("\n".join(out).rstrip("\n") + "\n")


main()
PY

echo "wrote $out"
