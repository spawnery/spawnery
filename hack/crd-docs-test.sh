#!/usr/bin/env bash
# Drives hack/crd-docs.sh against the CRDs checked into this tree; only the
# real schema shows a stop-list field renamed underneath it.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
gen="$root/hack/crd-docs.sh"
page="$root/docs/reference/crds.md"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

failures=0
run() {
  local name="$1" want="$2"; shift 2
  local out status
  out="$("$@" 2>&1)" && status=0 || status=$?
  if [ "$status" -ne "$want" ]; then
    echo "FAIL $name: exit $status, want $want"
    printf '%s\n' "$out" | sed 's/^/    /'
    failures=$((failures + 1))
  else
    echo "ok   $name"
  fi
}
has() {
  local name="$1" needle="$2"
  if grep -qF -- "$needle" "$page"; then
    echo "ok   $name"
  else
    echo "FAIL $name: $page does not contain '$needle'"
    failures=$((failures + 1))
  fi
}

# Otherwise a generator that wrote nothing leaves the committed copy to pass.
rm -f "$page"

run "the generator runs and every stop-list entry resolves" 0 "$gen"

if [ -f "$page" ]; then
  echo "ok   the page was written this run"
else
  echo "FAIL the page was written this run: $page is missing after a fresh run"
  failures=$((failures + 1))
fi

first_line="$(head -1 "$page" 2>/dev/null || true)"
case "$first_line" in
  *"Generated by"*) echo "ok   the first line is the generated-by header" ;;
  *)
    echo "FAIL the first line is the generated-by header: got '$first_line'"
    failures=$((failures + 1))
    ;;
esac

for kind in Network ServerGroup ProxyGroup Server ScaleBoost; do
  has "the page names $kind" "## $kind"
done

# Matched by <code> tag: "type" and "config" also appear in prose.
for field in expose routing resources maxPlayers type config; do
  has "the page carries spec.$field" ">$field<"
done

# forwardingSecretRef is multi-paragraph; defaults.minecraftVersion is one
# sentence and must render without <details>.
row="$(grep -F '<code>forwardingSecretRef</code>' "$page" || true)"
case "$row" in
  *"<details>"*) echo "ok   a multi-paragraph description collapses behind <details>" ;;
  *)
    echo "FAIL a multi-paragraph description collapses behind <details>: no <details> in its row"
    failures=$((failures + 1))
    ;;
esac
row="$(grep -F '<code>defaults.minecraftVersion</code>' "$page" || true)"
case "$row" in
  *"<details>"*)
    echo "FAIL a single-paragraph description has no <details>: found one anyway"
    failures=$((failures + 1))
    ;;
  *) echo "ok   a single-paragraph description has no <details>" ;;
esac

if [ -f "$page" ] && cp "$page" "$tmp/first-run.md" && "$gen" > /dev/null && cp "$page" "$tmp/second-run.md"; then
  if diff -u "$tmp/first-run.md" "$tmp/second-run.md" > "$tmp/diff"; then
    echo "ok   two runs produce identical output"
  else
    echo "FAIL two runs produce identical output:"
    sed 's/^/    /' "$tmp/diff"
    failures=$((failures + 1))
  fi
else
  echo "FAIL two runs produce identical output: could not produce two runs to compare"
  failures=$((failures + 1))
fi

if [ "$failures" -ne 0 ]; then
  echo "$failures case(s) failed"
  exit 1
fi
echo "all cases passed"
