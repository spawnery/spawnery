#!/usr/bin/env bash
# Turns controller-gen's output into the two chart templates that must not be
# written by hand.
#
#   role.yaml  -> templates/rbac.yaml, namespace replaced by the release's.
#                 controller-gen emits a Role only when the markers name some
#                 namespace, so the literal there is a placeholder.
#   crd/bases/ -> templates/crds.yaml, helm.sh/resource-policy: keep on every
#                 CRD. templates/ rather than crds/ so `helm upgrade` carries
#                 schema changes; the annotation stops `helm uninstall` from
#                 deleting every object of those kinds.
set -euo pipefail

cd "$(dirname "$0")/.."

roles_in="config/rbac/role.yaml"
crds_in="config/crd/bases"
out_dir="charts/spawnery/templates"

header='# Generated by hack/chart-templates.sh via `make manifests`. Do not edit:
# your changes are lost the next time controller-gen runs.'

# --- rbac.yaml ------------------------------------------------------------
if ! grep -q '^  namespace: spawnery-system$' "$roles_in"; then
	echo "hack/chart-templates.sh: $roles_in has no '  namespace: spawnery-system' line." >&2
	echo "controller-gen's output changed shape, or a marker lost its namespace= argument." >&2
	exit 1
fi

{
	echo "$header"
	sed 's|^  namespace: spawnery-system$|  namespace: {{ .Release.Namespace }}|' "$roles_in"
} > "$out_dir/rbac.yaml"

# --- crds.yaml ------------------------------------------------------------
crd_files=0
{
	echo "$header"
	for f in "$crds_in"/*.yaml; do
		if ! grep -q '^  annotations:$' "$f"; then
			echo "hack/chart-templates.sh: $f has no top-level annotations block." >&2
			exit 1
		fi
		crd_files=$((crd_files + 1))
		echo "---"
		sed '0,/^  annotations:$/s|^  annotations:$|  annotations:\n    helm.sh/resource-policy: keep|' "$f"
	done
} > "$out_dir/crds.yaml"

# --- the postconditions ---------------------------------------------------
#
# The guards above check the input; a `sed` that never fired passes them too.
# A missing keep annotation installs and lints like a correct one and only
# shows at `helm uninstall`; nothing else in the repository checks it.
if [ "$crd_files" -eq 0 ]; then
	echo "hack/chart-templates.sh: $crds_in matched no *.yaml files; crds.yaml would ship no CRDs at all." >&2
	exit 1
fi
kept="$(grep -c '^    helm.sh/resource-policy: keep$' "$out_dir/crds.yaml" || true)"
if [ "$kept" -ne "$crd_files" ]; then
	echo "hack/chart-templates.sh: $out_dir/crds.yaml carries helm.sh/resource-policy: keep $kept time(s) for $crd_files CRD file(s)." >&2
	echo "The annotation transform did not apply to every file. \`helm uninstall\` would delete the unannotated CRDs and every object of their kinds in the cluster." >&2
	exit 1
fi

templated="$(grep -c '^  namespace: {{ .Release.Namespace }}$' "$out_dir/rbac.yaml" || true)"
if [ "$templated" -ne 1 ]; then
	echo "hack/chart-templates.sh: $out_dir/rbac.yaml has $templated templated namespace lines, want exactly 1." >&2
	exit 1
fi
if grep -q 'spawnery-system' "$out_dir/rbac.yaml"; then
	echo "hack/chart-templates.sh: $out_dir/rbac.yaml still carries the literal spawnery-system." >&2
	echo "The namespace transform did not apply. The Role would install into a namespace holding no operator." >&2
	exit 1
fi

echo "wrote $out_dir/rbac.yaml and $out_dir/crds.yaml"
