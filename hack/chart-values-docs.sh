#!/usr/bin/env bash
# Renders docs/reference/chart-values.md from charts/spawnery/values.schema.json,
# with defaults read from charts/spawnery/values.yaml.
#
# Run by `make manifests`, after hack/crd-docs.sh. Same shape as that script:
# a thin bash entry point around an embedded Python program, which is where
# the schema walk lives.
set -euo pipefail

cd "$(dirname "$0")/.."

schema="charts/spawnery/values.schema.json"
values="charts/spawnery/values.yaml"
out="docs/reference/chart-values.md"

python3 - "$schema" "$values" "$out" <<'PY'
import html
import json
import re
import sys

import yaml

schema_path, values_path, out_path = sys.argv[1], sys.argv[2], sys.argv[3]

HEADER = (
    "<!-- Generated by `hack/chart-values-docs.sh` via `make manifests`. Do not\n"
    "     edit: your changes are lost the next time it runs. -->"
)

URL_RE = re.compile(r"https?://[^\s<>\"]+")
CODE_SPAN_RE = re.compile(r"`([^`]+)`")


def render_description(text):
    if not text:
        return ""
    paragraphs = [p.strip() for p in text.strip().split("\n\n") if p.strip()]
    rendered = []
    for p in paragraphs:
        p = " ".join(line.strip() for line in p.splitlines())
        p = html.escape(p)
        p = CODE_SPAN_RE.sub(lambda m: f"<code>{m.group(1)}</code>", p)
        p = URL_RE.sub(lambda m: f'<a href="{m.group(0)}">{m.group(0)}</a>', p)
        rendered.append(p)
    if len(rendered) <= 1:
        return rendered[0] if rendered else ""
    # Same cut as hack/crd-docs.sh: the first paragraph, never a word count.
    # No description in this schema is multi-paragraph today, so this branch
    # is untested by the current data -- kept for the field that eventually
    # is, rather than left for that day to discover the table has no answer.
    first, rest = rendered[0], rendered[1:]
    return first + "<details><summary>more</summary>" + "<br><br>".join(rest) + "</details>"


PY_TO_JSON_TYPE = {bool: "boolean", int: "integer", float: "number", str: "string"}


def type_of(schema):
    t = schema.get("type")
    if t is None and "enum" in schema and schema["enum"]:
        # values.schema.json states a couple of enums (pullPolicy) with no
        # "type" alongside -- valid JSON Schema, since the enum already
        # constrains the value -- but leaving type_of to fall through to
        # its object default here would call a plain string field an object.
        t = PY_TO_JSON_TYPE.get(type(schema["enum"][0]), "string")
    if t == "array":
        items = schema.get("items", {}) or {}
        if items.get("type") == "object" and "properties" in items:
            return "array"
        return f"array of {type_of(items)}" if items else "array"
    if t == "object" or t is None:
        if "properties" in schema:
            return "object"
        ap = schema.get("additionalProperties")
        if isinstance(ap, dict):
            return f"map[string]{type_of(ap)}"
        return "map[string]string" if ap else "object"
    fmt = schema.get("format")
    return f"{t} ({fmt})" if fmt else t


def constraints_of(schema):
    notes = []
    if "enum" in schema:
        notes.append("one of: " + ", ".join(str(v) for v in schema["enum"]))
    if "minimum" in schema or "maximum" in schema:
        lo, hi = schema.get("minimum"), schema.get("maximum")
        notes.append(f"{lo if lo is not None else ''}-{hi}" if hi is not None else f">= {lo}")
    if "minLength" in schema or "maxLength" in schema:
        lo, hi = schema.get("minLength"), schema.get("maxLength")
        notes.append(f"length {lo if lo is not None else 0}-{hi}" if hi is not None else f"length >= {lo}")
    if "minItems" in schema:
        notes.append(f"at least {schema['minItems']} item(s)")
    if "pattern" in schema:
        notes.append(f"pattern <code>{html.escape(schema['pattern'])}</code>")
    return notes


def type_cell(schema):
    base = type_of(schema)
    notes = constraints_of(schema)
    if not notes:
        return html.escape(base)
    return f"{html.escape(base)} ({'; '.join(n if '<code>' in n else html.escape(n) for n in notes)})"


def format_value(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if v is None:
        return "null"
    if isinstance(v, (dict, list)):
        # Flow style, unwrapped: PyYAML line-wraps a long default-style value
        # with a backslash continuation, unreadable once html-escaped into a
        # single table cell. See hack/crd-docs.sh's default_cell for the twin
        # of this.
        return yaml.safe_dump(v, default_flow_style=True, sort_keys=False, width=10**6).strip()
    return str(v)


def default_cell(value_path, values):
    if value_path is None:
        return ""
    node = values
    for part in value_path:
        if not isinstance(node, dict) or part not in node:
            return ""
        node = node[part]
    return f"<code>{html.escape(format_value(node))}</code>"


def walk(props, prefix, value_prefix, rows, values):
    for name, prop_schema in (props or {}).items():
        disp_path = f"{prefix}.{name}" if prefix else name
        value_path = None if value_prefix is None else value_prefix + [name]
        rows.append({
            "path": disp_path,
            "type": type_cell(prop_schema),
            "default": default_cell(value_path, values),
            "description": render_description(prop_schema.get("description", "")),
        })
        t = prop_schema.get("type")
        if t == "object" and "properties" in prop_schema:
            walk(prop_schema["properties"], disp_path, value_path, rows, values)
        elif t == "array":
            items = prop_schema.get("items", {}) or {}
            if items.get("type") == "object" and "properties" in items:
                # Item fields have no default of their own to look up:
                # values.yaml's own list is empty, and an item template is
                # not a value. This is also why networkNamespaces itself
                # still gets a row above -- the array's own default ([]) is
                # real, its items' are not.
                walk(items["properties"], disp_path + "[]", None, rows, values)


def render_table(rows):
    out = ['<div style="overflow-x: auto;"><table>']
    out.append("<thead><tr><th>Key</th><th>Type</th><th>Default</th><th>Description</th></tr></thead>")
    out.append("<tbody>")
    for row in rows:
        out.append(
            "<tr>"
            f"<td><code>{html.escape(row['path'])}</code></td>"
            f"<td>{row['type']}</td>"
            f"<td>{row['default']}</td>"
            f"<td>{row['description']}</td>"
            "</tr>"
        )
    out.append("</tbody></table></div>")
    return "\n".join(out)


def main():
    with open(schema_path) as f:
        schema = json.load(f)
    with open(values_path) as f:
        values = yaml.safe_load(f) or {}

    rows = []
    walk(schema.get("properties", {}), "", [], rows, values)

    required = schema.get("required", [])

    out = [HEADER, "", "# Chart values", ""]
    out.append(
        "Generated from `charts/spawnery/values.schema.json` -- the schema Helm "
        "validates every install and `--set` against -- with defaults read from "
        "`charts/spawnery/values.yaml`, the chart's own shipped copy."
    )
    out.append("")
    if schema.get("description"):
        out.append(render_description(schema["description"]))
        out.append("")
    if required:
        out.append(
            "Required at the top level: " + ", ".join(f"`{k}`" for k in required) + "."
        )
        out.append("")
    out.append(
        "A blank Description is not a gap: the schema describes only what "
        "needs it, and leaves a key bare when its name and type already say "
        "what it is."
    )
    out.append("")
    out.append(render_table(rows))
    out.append("")

    with open(out_path, "w") as f:
        f.write("\n".join(out).rstrip("\n") + "\n")


main()
PY

echo "wrote $out"
